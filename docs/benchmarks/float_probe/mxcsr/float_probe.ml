// Targeted raw-tree and raw-loop checks for the removed final float probe compare.
// MXCSR is read before result inspection and restored before formatting.
extern function phase9_mxcsr_read() from "libphase9_mxcsr.so" returns u32
extern function phase9_mxcsr_write(value as u32) from "libphase9_mxcsr.so" returns void
extern function phase9_box(hi as u32, lo as u32) from "libphase9_mxcsr.so" returns ptr
extern function phase9_payload_low(value as u64) from "libphase9_mxcsr.so" returns u32
extern function phase9_payload_high(value as u64) from "libphase9_mxcsr.so" returns u32

function treeLeft(a as float, b as float, scale as float)
  return (a + b) * scale
end function
function treeRight(a as float, b as float, scale as float)
  return scale * (a + b)
end function
function treeBoth(a as float, b as float, c as float, d as float)
  return (a + b) * (c + d)
end function
function treeCompareLeft(a as float, b as float, bound as float)
  return (a + b) <= bound
end function
function treeCompareRight(a as float, b as float, bound as float)
  return bound <= (a + b)
end function
function loopLeft(n as int, x as float, y as float, scale as float)
  i as int = 0
  while i < n
    x = (x + y) * scale
    i = i + 1
  end while
  return [x, i]
end function
function loopRight(n as int, x as float, y as float, scale as float)
  i as int = 0
  while i < n
    x = scale * (x + y)
    i = i + 1
  end while
  return [x, i]
end function
function loopCondition(n as int, a as float, b as float, bound as float, x as float)
  i as int = 0
  while i < n and (a + b) <= bound
    x = x * 0.5 + 0.123456789012345
    i = i + 1
  end while
  return [x, i]
end function
function record(mode, name, flags, value, iterations)
  raw = nativeRawValue(value)
  tag = raw & 7
  kind = typeof(value)
  integerValue = 0
  low = 0
  high = 0
  if kind == "int" then
    integerValue = value
  else
    low = phase9_payload_low(raw)
    high = phase9_payload_high(raw)
  end if
  print mode + ":" + name + ":" + flags + ":" + kind + ":" + tag + ":" + low + ":" + high + ":" + integerValue + ":" + iterations
end function
