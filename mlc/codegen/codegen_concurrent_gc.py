"""Optional Windows snapshot-at-the-beginning collector and deletion log.

The persistent native worker never enters managed application code. Keep helper
emission order, register preservation and data layout identical to the ML port.
"""

SATB_CAPACITY = 1048576
HEAP_LOCK_DEPTH = 208


class CodegenConcurrentGC:
    """Emit the worker, request/wait protocol and allocation-free SATB helpers."""

    def _gc_satb_capacity(self):
        """Capacity is in qwords; clamp the diagnostic byte limit before division."""
        return min(67108864, max(64, int(self.heap_config.get('gc_satb_limit_bytes', SATB_CAPACITY * 8)))) // 8

    def ensure_concurrent_gc_data(self):
        """Materialize optional worker state without changing default-mode data."""
        self.ensure_gc_data()
        for name in ["gc_concurrent_handle", "gc_concurrent_go", "gc_concurrent_done", "gc_concurrent_frontier", "gc_concurrent_free_head", "gc_concurrent_free_tail", "gc_concurrent_pause_start", "gc_satb_active", "gc_satb_count", "gc_satb_lock", "gc_satb_overflow", "gc_reuse_bits", "gc_reuse_capacity", "gc_reuse_min"]:
            if name not in self.data.labels:
                self.data.add_u64(name, 0)
        if 'gc_concurrent_context' not in self.data.labels:
            self.data.pad_align(8)
            self.data.add_bytes('gc_concurrent_context', bytes(216))
        if 'gc_free_bins' not in self.data.labels:
            self.data.pad_align(8)
            self.data.add_bytes('gc_free_bins', bytes(512))
        if 'gc_satb_buffer' not in self.bss.labels:
            self.bss.reserve('gc_satb_buffer', self._gc_satb_capacity() * 8, align=8)

    def emit_concurrent_gc_satb_record(self):
        """Emit a nonallocating leaf that logs RAX and preserves all registers."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_satb_record")
        a.push_reg("rcx")
        a.mov_r64_r64("rcx", "rax")
        a.mov_rax_rip_qword("gc_satb_active")
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "satb_record_done")
        a.test_r64_imm32("rcx", 7)
        a.jcc("ne", "satb_record_done")
        a.mov_rax_rip_qword("heap_base")
        a.add_r64_imm("rax", 8)
        a.cmp_r64_r64("rcx", "rax")
        a.jcc("b", "satb_record_done")
        a.mov_rax_rip_qword("gc_concurrent_frontier")
        a.cmp_r64_r64("rcx", "rax")
        a.jcc("ae", "satb_record_done")
        a.push_reg("rdx")
        a.push_reg("r10")
        a.push_reg("r11")
        a.mov_r64_r64("r10", "rcx")
        # Marked values (including gray objects) already belong to the snapshot.
        # Filtering these duplicate deletions bounds log growth and worker traffic.
        a.mov_rax_rip_qword("heap_base")
        a.mov_r64_r64("r11", "rcx")
        a.sub_r64_r64("r11", "rax")
        a.sub_r64_imm("r11", 8)
        a.shr_r64_imm8("r11", 3)
        a.mov_r64_r64("rdx", "r11")
        a.shr_r64_imm8("rdx", 6)
        # Allocations in snapshot-free ranges are born outside this cycle.
        # The immutable exclusion bitmap also avoids logging their deletions.
        a.mov_rax_rip_qword("gc_reuse_min")
        a.cmp_r64_r64("rcx", "rax")
        a.jcc("b", "satb_record_snapshot")
        a.mov_rax_rip_qword("gc_reuse_bits")
        a.mov_r64_mem_bis("rax", "rax", "rdx", 8, 0)
        a.bt_r64_r64("rax", "r11")
        a.jcc("b", "satb_record_restore")
        a.mark("satb_record_snapshot")
        a.mov_rax_rip_qword("gc_mark_bits_base")
        a.mov_r64_mem_bis("rax", "rax", "rdx", 8, 0)
        a.bt_r64_r64("rax", "r11")
        a.jcc("b", "satb_record_restore")
        a.lea_r64_rip("r11", "gc_satb_lock")
        a.mark("satb_record_lock")
        a.xor_r32_r32("eax", "eax")
        a.mov_r32_imm32("edx", 1)
        a.lock_cmpxchg_membase_disp_r32("r11", 0, "edx")
        a.jcc("e", "satb_record_owned")
        a.emit(bytes.fromhex("f390"))
        a.jmp("satb_record_lock")
        a.mark("satb_record_owned")
        a.mov_rax_rip_qword("gc_satb_count")
        a.cmp_r64_imm("rax", self._gc_satb_capacity())
        a.jcc("ae", "satb_record_overflow")
        a.lea_r64_rip("rdx", "gc_satb_buffer")
        a.mov_mem_bis_r64("rdx", "rax", 8, 0, "r10")
        a.inc_r64("rax")
        a.mov_rip_qword_rax("gc_satb_count")
        a.jmp("satb_record_unlock")
        a.mark("satb_record_overflow")
        # Never drop an edge and then reclaim. Overflow retains the entire snapshot.
        a.mov_rax_imm64(1)
        a.mov_rip_qword_rax("gc_satb_overflow")
        a.mark("satb_record_unlock")
        a.mov_membase_disp_imm32("r11", 0, 0, qword=False)
        a.mark("satb_record_restore")
        a.pop_reg("r11")
        a.pop_reg("r10")
        a.pop_reg("rdx")
        a.mark("satb_record_done")
        a.mov_r64_r64("rax", "rcx")
        a.pop_reg("rcx")
        a.ret()
        return

    def emit_concurrent_gc_satb_pop(self):
        """Pop one logged reference under the spinlock; return zero when empty."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_satb_pop")
        a.lea_r64_rip("r11", "gc_satb_lock")
        a.mark("satb_pop_lock")
        a.xor_r32_r32("eax", "eax")
        a.mov_r32_imm32("edx", 1)
        a.lock_cmpxchg_membase_disp_r32("r11", 0, "edx")
        a.jcc("e", "satb_pop_owned")
        a.emit(bytes.fromhex("f390"))
        a.jmp("satb_pop_lock")
        a.mark("satb_pop_owned")
        a.mov_rax_rip_qword("gc_satb_count")
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "satb_pop_empty")
        a.dec_r64("rax")
        a.mov_rip_qword_rax("gc_satb_count")
        a.lea_r64_rip("rdx", "gc_satb_buffer")
        a.mov_r64_mem_bis("rax", "rdx", "rax", 8, 0)
        a.mark("satb_pop_empty")
        a.mov_membase_disp_imm32("r11", 0, 0, qword=False)
        a.ret()
        return

    def emit_concurrent_gc_free_push(self):
        """Insert free header RAX by floor(log2(size)); preserve all registers."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_free_push")
        for reg in ("rax", "rcx", "rdx", "r10", "r11"):
            a.push_reg(reg)
        a.mov_r64_r64("r10", "rax")
        a.mov_r64_membase_disp("rax", "r10", 0)
        a.and_r64_imm("rax", -8)
        a.mov_r64_r64("rdx", "rax")
        a.shr_r64_imm8("rdx", 32)
        a.test_r32_r32("edx", "edx")
        a.jcc("e", "gc_free_push_low")
        a.bsr_r32_r32("edx", "edx")
        a.add_r64_imm("rdx", 32)
        a.jmp("gc_free_push_index")
        a.mark("gc_free_push_low")
        a.bsr_r32_r32("edx", "eax")
        a.mark("gc_free_push_index")
        a.lea_r64_rip("r11", "gc_free_bins")
        a.mov_r64_mem_bis("rcx", "r11", "rdx", 8, 0)
        a.mov_membase_disp_r64("r10", 8, "rcx")
        a.mov_mem_bis_r64("r11", "rdx", 8, 0, "r10")
        for reg in ("r11", "r10", "rdx", "rcx", "rax"):
            a.pop_reg(reg)
        a.ret()

    def emit_concurrent_gc_free_merge(self):
        """Move a detached list at RAX into size bins under the heap monitor."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.add("fn_gc_free_push")
        a.mark("fn_gc_free_merge")
        a.sub_rsp_imm8(0x28)
        a.mark("gc_free_merge_loop")
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_free_merge_done")
        a.mov_r64_membase_disp("r10", "rax", 8)
        a.call("fn_gc_free_push")
        a.mov_r64_r64("rax", "r10")
        a.jmp("gc_free_merge_loop")
        a.mark("gc_free_merge_done")
        a.add_rsp_imm8(0x28)
        a.ret()

    def emit_concurrent_gc_free_flatten(self):
        """Detach all bins into gc_free_head only while preparing a snapshot."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_free_flatten")
        a.mov_rax_rip_qword("gc_free_head")
        a.lea_r64_rip("r11", "gc_free_bins")
        a.xor_r32_r32("ecx", "ecx")
        a.mark("gc_free_flatten_bin")
        a.mov_r64_mem_bis("r8", "r11", "rcx", 8, 0)
        a.xor_r32_r32("edx", "edx")
        a.mov_mem_bis_r64("r11", "rcx", 8, 0, "rdx")
        a.test_r64_r64("r8", "r8")
        a.jcc("e", "gc_free_flatten_next")
        a.mov_r64_r64("r9", "r8")
        a.mark("gc_free_flatten_tail")
        a.mov_r64_membase_disp("rdx", "r9", 8)
        a.test_r64_r64("rdx", "rdx")
        a.jcc("e", "gc_free_flatten_link")
        a.mov_r64_r64("r9", "rdx")
        a.jmp("gc_free_flatten_tail")
        a.mark("gc_free_flatten_link")
        a.mov_membase_disp_r64("r9", 8, "rax")
        a.mov_r64_r64("rax", "r8")
        a.mark("gc_free_flatten_next")
        a.inc_r64("rcx")
        a.cmp_r64_imm("rcx", 64)
        a.jcc("b", "gc_free_flatten_bin")
        a.mov_rip_qword_rax("gc_free_head")
        a.ret()

    def emit_concurrent_gc_free_take(self):
        """Pop the smallest suitable size class; allow >=4 KiB partial TLABs.

        RCX is desired size, RDX is the TLAB flag. Return header R8 (or zero),
        block size RDX and actual request RCX. Caller holds the heap monitor.
        """
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_free_take")
        a.mov_r64_r64("rax", "rcx")
        a.test_r64_r64("rdx", "rdx")
        a.jcc("e", "gc_free_take_class")
        # A refill is a capacity preference, not a user-visible 64 KiB object.
        # Reuse almost-full retired TLABs instead of cutting large buffer holes.
        a.mov_r32_imm32("eax", 4096)
        a.mark("gc_free_take_class")
        a.mov_r64_r64("r9", "rax")
        a.shr_r64_imm8("r9", 32)
        a.test_r32_r32("r9d", "r9d")
        a.jcc("e", "gc_free_take_low")
        a.bsr_r32_r32("r9d", "r9d")
        a.add_r64_imm("r9", 32)
        a.jmp("gc_free_take_bin")
        a.mark("gc_free_take_low")
        a.bsr_r32_r32("r9d", "eax")
        a.mark("gc_free_take_bin")
        a.lea_r64_rip("r11", "gc_free_bins")
        a.lea_r64_mem_bis("r10", "r11", "r9", 8, 0)
        a.mark("gc_free_take_node")
        a.mov_r64_membase_disp("r8", "r10", 0)
        a.test_r64_r64("r8", "r8")
        a.jcc("e", "gc_free_take_next_bin")
        if self._uses_gc_stats():
            a.mov_rax_rip_qword("gc_free_probes")
            a.inc_r64("rax")
            a.mov_rip_qword_rax("gc_free_probes")
        a.mov_r64_membase_disp("rdx", "r8", 0)
        a.and_r64_imm("rdx", -8)
        # A 64 KiB request visits smaller bins only in TLAB refill mode.
        a.cmp_r64_imm("r9", 16)
        a.jcc("ae", "gc_free_take_exact")
        a.cmp_r64_r64("rdx", "rcx")
        a.jcc("ae", "gc_free_take_found")
        # For ordinary small allocations, the first bin can be undersized.
        # Ordinary 64 KiB objects start at bin 16 and cannot take this path.
        a.cmp_r64_imm("rcx", 65536)
        a.jcc("ne", "gc_free_take_advance")
        a.mov_r64_r64("rcx", "rdx")
        a.jmp("gc_free_take_found")
        a.mark("gc_free_take_exact")
        a.cmp_r64_r64("rdx", "rcx")
        a.jcc("ae", "gc_free_take_found")
        a.mark("gc_free_take_advance")
        a.lea_r64_membase_disp("r10", "r8", 8)
        a.jmp("gc_free_take_node")
        a.mark("gc_free_take_next_bin")
        a.inc_r64("r9")
        a.cmp_r64_imm("r9", 64)
        a.jcc("b", "gc_free_take_bin")
        a.ret()
        a.mark("gc_free_take_found")
        a.mov_r64_membase_disp("rax", "r8", 8)
        a.mov_membase_disp_r64("r10", 0, "rax")
        a.ret()

    def emit_concurrent_gc_free_stats(self):
        """Return validated bin count RAX, byte sum RDX and largest block RCX."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_free_stats")
        for reg in ("rbx", "rsi", "rdi"):
            a.push_reg(reg)
        a.xor_r32_r32("eax", "eax")
        a.xor_r32_r32("edx", "edx")
        a.xor_r32_r32("ecx", "ecx")
        a.xor_r32_r32("ebx", "ebx")
        a.lea_r64_rip("rsi", "gc_free_bins")
        a.mov_rax_rip_qword("heap_base")
        a.mov_r64_r64("r11", "rax")
        a.mov_rax_rip_qword("heap_ptr")
        a.mov_r64_r64("r10", "rax")
        a.xor_r32_r32("eax", "eax")
        a.mov_r64_r64("r9", "r10")
        a.sub_r64_r64("r9", "r11")
        a.shr_r64_imm8("r9", 4)
        a.mark("gc_free_stats_bin")
        a.mov_r64_mem_bis("r8", "rsi", "rbx", 8, 0)
        a.mark("gc_free_stats_node")
        a.test_r64_r64("r8", "r8")
        a.jcc("e", "gc_free_stats_next")
        a.test_r64_r64("r9", "r9")
        a.jcc("e", "gc_free_stats_bad")
        a.dec_r64("r9")
        a.cmp_r64_r64("r8", "r11")
        a.jcc("b", "gc_free_stats_bad")
        # Reject high invalid pointers before header-end arithmetic can wrap.
        a.cmp_r64_r64("r8", "r10")
        a.jcc("ae", "gc_free_stats_bad")
        a.lea_r64_membase_disp("rdi", "r8", 16)
        a.cmp_r64_r64("rdi", "r10")
        a.jcc("a", "gc_free_stats_bad")
        a.test_r64_imm32("r8", 7)
        a.jcc("ne", "gc_free_stats_bad")
        a.mov_r64_membase_disp("rdi", "r8", 0)
        a.test_r64_imm32("rdi", 1)
        a.jcc("e", "gc_free_stats_bad")
        a.and_r64_imm("rdi", -8)
        a.cmp_r64_imm("rdi", 16)
        a.jcc("b", "gc_free_stats_bad")
        a.add_r64_r64("rdi", "r8")
        a.jcc("b", "gc_free_stats_bad")
        a.cmp_r64_r64("rdi", "r10")
        a.jcc("a", "gc_free_stats_bad")
        a.sub_r64_r64("rdi", "r8")
        a.inc_r64("rax")
        a.add_r64_r64("rdx", "rdi")
        a.cmp_r64_r64("rcx", "rdi")
        a.jcc("ae", "gc_free_stats_size")
        a.mov_r64_r64("rcx", "rdi")
        a.mark("gc_free_stats_size")
        a.mov_r64_membase_disp("r8", "r8", 8)
        a.jmp("gc_free_stats_node")
        a.mark("gc_free_stats_next")
        a.inc_r64("rbx")
        a.cmp_r64_imm("rbx", 64)
        a.jcc("b", "gc_free_stats_bin")
        a.jmp("gc_free_stats_done")
        a.mark("gc_free_stats_bad")
        a.xor_r32_r32("eax", "eax")
        a.xor_r32_r32("edx", "edx")
        a.xor_r32_r32("ecx", "ecx")
        a.mark("gc_free_stats_done")
        for reg in ("rdi", "rsi", "rbx"):
            a.pop_reg(reg)
        a.ret()

    def emit_concurrent_gc_heap_free_stat(self, byte_sum):
        """Emit the public free-byte/count query over all size bins."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.update(["fn_heap_enter", "fn_heap_leave", "fn_gc_free_stats"])
        label = "fn_heap_free_blocks"
        if byte_sum:
            label = "fn_heap_free_bytes"
        a.mark(label)
        a.sub_rsp_imm8(0x28)
        a.call("fn_heap_enter")
        a.call("fn_gc_free_stats")
        if byte_sum:
            a.mov_r64_r64("rax", "rdx")
        a.shl_rax_imm8(3)
        a.or_rax_imm8(1)
        a.call("fn_heap_leave")
        a.add_rsp_imm8(0x28)
        a.ret()

    def emit_concurrent_gc_reuse_end(self):
        """Return the end of the protected run containing header RAX (leaf)."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        a.mark("fn_gc_reuse_end")
        a.mov_rdx_rip_qword("heap_base")
        a.sub_r64_r64("rax", "rdx")
        a.shr_r64_imm8("rax", 3)
        a.mov_r64_r64("rcx", "rax")
        a.shr_r64_imm8("rax", 6)
        a.mov_r64_r64("r8", "rax")
        a.mov_rax_rip_qword("gc_reuse_bits")
        a.mov_r64_r64("r9", "rax")
        a.mov_r64_mem_bis("rax", "r9", "r8", 8, 0)
        # Ignore bits before the requested header in its first bitmap word.
        a.mov_r64_imm64("r11", -1)
        a.shl_r64_cl("r11")
        a.xor_r64_imm("r11", -1)
        a.or_r64_r64("rax", "r11")
        a.mark("gc_reuse_end_word")
        a.xor_r64_imm("rax", -1)
        a.test_r64_r64("rax", "rax")
        a.jcc("ne", "gc_reuse_end_bit")
        a.inc_r64("r8")
        a.mov_r64_mem_bis("rax", "r9", "r8", 8, 0)
        a.jmp("gc_reuse_end_word")
        a.mark("gc_reuse_end_bit")
        # BSF32 works on baseline x64; no BMI/POPCNT or AVX requirement.
        a.xor_r32_r32("r11d", "r11d")
        a.test_r32_r32("eax", "eax")
        a.jcc("ne", "gc_reuse_end_low")
        a.shr_r64_imm8("rax", 32)
        a.mov_r32_imm32("r11d", 32)
        a.mark("gc_reuse_end_low")
        a.bsf_r32_r32("eax", "eax")
        a.add_r64_r64("rax", "r11")
        a.shl_r64_imm8("r8", 6)
        a.add_r64_r64("rax", "r8")
        a.shl_rax_imm8(3)
        a.add_r64_r64("rax", "rdx")
        a.ret()

    def emit_concurrent_gc_reuse_snapshot(self):
        """Protect and coalesce central free ranges while all mutators are parked."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.update(["fn_gc_reuse_end", "fn_gc_free_push"])
        a.mark("fn_gc_reuse_snapshot")
        for reg in ("rbx", "rbp", "rsi", "rdi", "r12", "r13", "r14", "r15"):
            a.push_reg(reg)
        a.sub_rsp_imm8(0x28)
        a.mov_rax_rip_qword("heap_base")
        a.mov_r64_r64("rbp", "rax")
        a.mov_rax_rip_qword("gc_concurrent_frontier")
        a.mov_rip_qword_rax("gc_reuse_min")
        a.sub_r64_r64("rax", "rbp")
        # One exclusion bit per 8 heap bytes, plus a zero sentinel word so
        # scanning a free run ending exactly on a bitmap page cannot overread.
        a.add_r64_imm("rax", 511)
        a.shr_r64_imm8("rax", 9)
        a.inc_r64("rax")
        a.shl_rax_imm8(3)
        a.mov_r64_r64("r13", "rax")
        a.mov_rax_rip_qword("gc_reuse_capacity")
        a.cmp_r64_r64("rax", "r13")
        a.jcc("ae", "gc_reuse_storage_ready")
        a.shl_rax_imm8(1)
        a.cmp_r64_r64("rax", "r13")
        a.jcc("ae", "gc_reuse_storage_size")
        a.mov_r64_r64("rax", "r13")
        a.mark("gc_reuse_storage_size")
        a.add_r64_imm("rax", 4095)
        a.and_r64_imm("rax", -4096)
        a.mov_r64_r64("r14", "rax")
        a.mov_r64_r64("rdx", "rax")
        a.xor_r32_r32("ecx", "ecx")
        a.mov_r8d_imm32(0x3000)
        a.mov_r9d_imm32(4)
        a.mov_rax_rip_qword("iat_VirtualAlloc")
        a.call_rax()
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_reuse_storage_failed")
        a.mov_r64_r64("r12", "rax")
        a.mov_rax_rip_qword("gc_reuse_bits")
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_reuse_storage_publish")
        a.mov_r64_r64("rcx", "rax")
        a.xor_r32_r32("edx", "edx")
        a.mov_r8d_imm32(0x8000)
        a.mov_rax_rip_qword("iat_VirtualFree")
        a.call_rax()
        a.mark("gc_reuse_storage_publish")
        a.mov_r64_r64("rax", "r12")
        a.mov_rip_qword_rax("gc_reuse_bits")
        a.mov_r64_r64("rax", "r14")
        a.mov_rip_qword_rax("gc_reuse_capacity")
        a.mark("gc_reuse_storage_ready")
        a.mov_rax_rip_qword("gc_reuse_bits")
        a.mov_r64_r64("r12", "rax")
        a.mov_r64_r64("rdi", "rax")
        a.mov_r64_r64("rcx", "r13")
        a.shr_r64_imm8("rcx", 3)
        a.xor_r32_r32("eax", "eax")
        a.rep_stosq()
        a.mov_rax_rip_qword("gc_free_head")
        a.mov_r64_r64("r14", "rax")
        a.xor_r32_r32("eax", "eax")
        a.mov_rip_qword_rax("gc_free_head")
        a.xor_r32_r32("r15d", "r15d")
        # Consume bins directly while constructing the exclusion bitmap.
        # Flattening first walked every cache-cold free header an extra time.
        a.lea_r64_rip("rbx", "gc_free_bins")
        a.mark("gc_reuse_protect_loop")
        a.test_r64_r64("r14", "r14")
        a.jcc("e", "gc_reuse_protect_bin")
        a.mov_r64_membase_disp("rsi", "r14", 8)
        a.mov_rax_rip_qword("gc_reuse_min")
        a.cmp_r64_r64("r14", "rax")
        a.jcc("ae", "gc_reuse_min_done")
        a.mov_r64_r64("rax", "r14")
        a.mov_rip_qword_rax("gc_reuse_min")
        a.mark("gc_reuse_min_done")
        a.mov_r64_r64("r8", "r14")
        a.sub_r64_r64("r8", "rbp")
        a.mov_r64_membase_disp("r9", "r14", 0)
        a.and_r64_imm("r9", -8)
        a.add_r64_r64("r9", "r8")
        a.shr_r64_imm8("r8", 3)
        a.shr_r64_imm8("r9", 3)
        a.dec_r64("r9")
        a.mov_r64_r64("rdx", "r8")
        a.shr_r64_imm8("rdx", 6)
        a.mov_r64_r64("r10", "r9")
        a.shr_r64_imm8("r10", 6)
        a.mov_r64_r64("rcx", "r8")
        a.mov_r64_imm64("r11", -1)
        a.shl_r64_cl("r11")
        a.and_r64_imm("r9", 63)
        a.mov_rcx_imm32(63)
        a.sub_r64_r64("rcx", "r9")
        a.mov_rax_imm64(-1)
        a.shr_r64_cl("rax")
        a.cmp_r64_r64("rdx", "r10")
        a.jcc("ne", "gc_reuse_multiple_words")
        a.and_r64_r64("rax", "r11")
        a.mov_r64_mem_bis("rcx", "r12", "rdx", 8, 0)
        a.or_r64_r64("rax", "rcx")
        a.mov_mem_bis_r64("r12", "rdx", 8, 0, "rax")
        a.jmp("gc_reuse_protect_next")
        a.mark("gc_reuse_multiple_words")
        a.mov_r64_mem_bis("rcx", "r12", "rdx", 8, 0)
        a.or_r64_r64("rcx", "r11")
        a.mov_mem_bis_r64("r12", "rdx", 8, 0, "rcx")
        a.mov_r64_mem_bis("rcx", "r12", "r10", 8, 0)
        a.or_r64_r64("rax", "rcx")
        a.mov_mem_bis_r64("r12", "r10", 8, 0, "rax")
        a.lea_r64_mem_bis("rdi", "r12", "rdx", 8, 8)
        a.mov_r64_r64("rcx", "r10")
        a.sub_r64_r64("rcx", "rdx")
        a.dec_r64("rcx")
        a.mov_rax_imm64(-1)
        a.rep_stosq()
        a.mark("gc_reuse_protect_next")
        a.mov_r64_r64("r14", "rsi")
        a.jmp("gc_reuse_protect_loop")
        a.mark("gc_reuse_protect_bin")
        a.cmp_r64_imm("r15", 64)
        a.jcc("ae", "gc_reuse_coalesce_begin")
        a.mov_r64_mem_bis("r14", "rbx", "r15", 8, 0)
        a.xor_r32_r32("eax", "eax")
        a.mov_mem_bis_r64("rbx", "r15", 8, 0, "rax")
        a.inc_r64("r15")
        a.jmp("gc_reuse_protect_loop")
        # Coalesce maximal runs from the compact immutable bitmap, avoiding a
        # second cache-cold walk through free headers. Publish each completed
        # run directly into its size bin, without another temporary list walk.
        a.mark("gc_reuse_coalesce_begin")
        a.mov_rax_rip_qword("gc_reuse_min")
        a.sub_r64_r64("rax", "rbp")
        a.shr_r64_imm8("rax", 3)
        a.mov_r64_r64("r14", "rax")
        a.mov_rax_rip_qword("gc_concurrent_frontier")
        a.sub_r64_r64("rax", "rbp")
        a.shr_r64_imm8("rax", 3)
        a.mov_r64_r64("r13", "rax")
        a.mark("gc_reuse_coalesce_loop")
        a.cmp_r64_r64("r14", "r13")
        a.jcc("ae", "gc_reuse_coalesce_done")
        a.mov_r64_r64("r8", "r14")
        a.shr_r64_imm8("r8", 6)
        a.mov_r64_mem_bis("rax", "r12", "r8", 8, 0)
        a.mov_r64_r64("rcx", "r14")
        a.mov_r64_imm64("rdx", -1)
        a.shl_r64_cl("rdx")
        a.and_r64_r64("rax", "rdx")
        a.test_r64_r64("rax", "rax")
        a.jcc("ne", "gc_reuse_coalesce_bit")
        a.or_r64_imm("r14", 63)
        a.inc_r64("r14")
        # Large live buffers leave long zero spans. Skip 128 bitmap bytes
        # together, bounded by the frozen frontier (baseline x64, no SIMD).
        a.mark("gc_reuse_coalesce_zero")
        a.mov_r64_r64("rax", "r14")
        a.add_r64_imm("rax", 1024)
        a.cmp_r64_r64("rax", "r13")
        a.jcc("a", "gc_reuse_coalesce_loop")
        a.mov_r64_r64("r8", "r14")
        a.shr_r64_imm8("r8", 6)
        a.mov_r64_mem_bis("rax", "r12", "r8", 8, 0)
        for offset in range(8, 128, 8):
            a.mov_r64_mem_bis("rdx", "r12", "r8", 8, offset)
            a.or_r64_r64("rax", "rdx")
        a.test_r64_r64("rax", "rax")
        a.jcc("ne", "gc_reuse_coalesce_loop")
        a.add_r64_imm("r14", 1024)
        a.jmp("gc_reuse_coalesce_zero")
        a.mark("gc_reuse_coalesce_bit")
        a.and_r64_imm("r14", -64)
        a.test_r32_r32("eax", "eax")
        a.jcc("ne", "gc_reuse_coalesce_low")
        a.shr_r64_imm8("rax", 32)
        a.add_r64_imm("r14", 32)
        a.mark("gc_reuse_coalesce_low")
        a.bsf_r32_r32("eax", "eax")
        a.add_r64_r64("r14", "rax")
        a.shl_r64_imm8("r14", 3)
        a.add_r64_r64("r14", "rbp")
        a.mov_r64_r64("rax", "r14")
        a.call("fn_gc_reuse_end")
        a.mov_r64_r64("rsi", "rax")
        a.sub_r64_r64("rax", "r14")
        a.or_r64_imm("rax", 1)
        a.mov_membase_disp_r64("r14", 0, "rax")
        a.mov_r64_r64("rax", "r14")
        a.call("fn_gc_free_push")
        a.mov_r64_r64("r14", "rsi")
        a.sub_r64_r64("r14", "rbp")
        a.shr_r64_imm8("r14", 3)
        a.jmp("gc_reuse_coalesce_loop")
        a.mark("gc_reuse_coalesce_done")
        a.xor_r32_r32("eax", "eax")
        a.mov_rip_qword_rax("gc_free_head")
        a.jmp("gc_reuse_snapshot_done")
        a.mark("gc_reuse_storage_failed")
        # Safe fallback to the old frozen-list policy if metadata allocation
        # fails. The frontier minimum disables every exclusion-bitmap read.
        a.xor_r32_r32("eax", "eax")
        a.mov_rip_qword_rax("gc_free_head")
        a.lea_r64_rip("rdi", "gc_free_bins")
        a.mov_rcx_imm32(64)
        a.rep_stosq()
        a.mark("gc_reuse_snapshot_done")
        a.add_rsp_imm8(0x28)
        for reg in ("r15", "r14", "r13", "r12", "rdi", "rsi", "rbp", "rbx"):
            a.pop_reg(reg)
        a.ret()

    def emit_concurrent_gc_worker(self):
        """Emit the native worker's private context and persistent event loop."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.update(["fn_gc_concurrent_cycle"])
        a.mark("fn_gc_concurrent_worker")
        a.sub_rsp_imm8(0x28)
        a.lea_rax_rip("gc_concurrent_context")
        a.mov_gs_qword_28_rax()
        a.mark("gc_worker_wait")
        a.mov_rax_rip_qword("gc_concurrent_go")
        a.mov_r64_r64("rcx", "rax")
        a.mov_r32_imm32("edx", -1)
        a.mov_rax_rip_qword("iat_WaitForSingleObject")
        a.call_rax()
        a.call("fn_gc_concurrent_cycle")
        a.jmp("gc_worker_wait")
        return

    def emit_concurrent_gc_request(self):
        """Coalesce requests under the monitor and return a completion sequence."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.update(["fn_gc_concurrent_worker", "fn_heap_enter", "fn_heap_leave"])
        a.mark("fn_gc_concurrent_request")
        a.sub_rsp_imm8(0x38)
        a.call("fn_heap_enter")
        a.mov_rax_rip_qword("gc_concurrent_phase")
        a.mov_membase_disp_r64("rsp", 0x30, "rax")
        a.test_r64_r64("rax", "rax")
        a.jcc("ne", "gc_request_return")
        a.mov_rax_rip_qword("gc_concurrent_handle")
        a.test_r64_r64("rax", "rax")
        a.jcc("ne", "gc_request_ready")
        # Both events are private unnamed Win32 handles.
        for name in ["gc_concurrent_go", "gc_concurrent_done"]:
            a.xor_r32_r32("ecx", "ecx")
            manual = 0
            if name == "gc_concurrent_done":
                manual = 1
            a.mov_r32_imm32("edx", manual)
            a.xor_r32_r32("r8d", "r8d")
            a.xor_r32_r32("r9d", "r9d")
            a.mov_rax_rip_qword("iat_CreateEventW")
            a.call_rax()
            a.test_r64_r64("rax", "rax")
            a.jcc("e", "gc_worker_init_failed")
            a.mov_rip_qword_rax(name)
        a.mov_membase_disp_imm32("rsp", 0x20, 0, qword=True)
        a.mov_membase_disp_imm32("rsp", 0x28, 0, qword=True)
        a.xor_r32_r32("ecx", "ecx")
        a.xor_r32_r32("edx", "edx")
        a.lea_r8_rip("fn_gc_concurrent_worker")
        a.xor_r32_r32("r9d", "r9d")
        a.mov_rax_rip_qword("iat_CreateThread")
        a.call_rax()
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_worker_init_failed")
        a.mov_rip_qword_rax("gc_concurrent_handle")
        a.mark("gc_request_ready")
        a.mov_rax_rip_qword("gc_concurrent_done")
        a.mov_r64_r64("rcx", "rax")
        a.mov_rax_rip_qword("iat_ResetEvent")
        a.call_rax()
        a.mov_rax_imm64(3)
        a.mov_rip_qword_rax("gc_concurrent_phase")
        a.mov_rax_rip_qword("gc_concurrent_go")
        a.mov_r64_r64("rcx", "rax")
        a.mov_rax_rip_qword("iat_SetEvent")
        a.call_rax()
        a.mark("gc_request_return")
        # Account another threshold only after allocations made since this request.
        a.xor_r32_r32("eax", "eax")
        a.mov_rip_qword_rax("gc_bytes_since")
        a.mov_rip_qword_rax("gc_young_bytes_since")
        a.mov_rax_rip_qword("gc_concurrent_completed")
        a.inc_r64("rax")
        a.call("fn_heap_leave")
        a.mov_r64_membase_disp("rdx", "rsp", 0x30)
        a.add_rsp_imm8(0x38)
        a.ret()
        a.mark("gc_worker_init_failed")
        a.mov_r32_imm32("ecx", 1)
        a.mov_rax_rip_qword("iat_ExitProcess")
        a.call_rax()
        return

    def emit_concurrent_gc_collect(self):
        """Wait for a fresh snapshot without retaining recursive monitor ownership."""
        a = self.asm
        self.ensure_concurrent_gc_data()
        self.used_helpers.update(["fn_gc_concurrent_request", "fn_gc_native_enter", "fn_gc_native_leave", "fn_heap_enter", "fn_heap_leave"])
        a.mark("fn_gc_collect")
        a.push_reg("rbx")
        a.push_reg("r12")
        a.sub_rsp_imm8(0x28)
        a.mov_r11_gs_qword_28()
        a.mov_r32_membase_disp("ebx", "r11", HEAP_LOCK_DEPTH)
        a.mov_r64_r64("r12", "rbx")
        a.mark("gc_collect_release")
        a.test_r64_r64("r12", "r12")
        a.jcc("e", "gc_collect_request")
        a.call("fn_heap_leave")
        a.dec_r64("r12")
        a.jmp("gc_collect_release")
        a.mark("gc_collect_request")
        a.call("fn_gc_concurrent_request")
        # If another cycle was already active, wait for it and then request a fresh
        # snapshot. Do not wait to observe an idle phase: continuous allocation can
        # legitimately request the next cycle before that observation is possible.
        a.mov_membase_disp_r64("rsp", 0x20, "rdx")
        a.mov_r64_r64("r12", "rax")
        a.mark("gc_collect_wait_enter")
        a.call("fn_gc_native_enter")
        a.mark("gc_collect_wait")
        a.mov_rax_rip_qword("gc_concurrent_completed")
        a.cmp_r64_r64("rax", "r12")
        a.jcc("ae", "gc_collect_restore")
        a.mov_rax_rip_qword("gc_concurrent_done")
        a.mov_r64_r64("rcx", "rax")
        a.mov_r32_imm32("edx", 10)
        a.mov_rax_rip_qword("iat_WaitForSingleObject")
        a.call_rax()
        a.jmp("gc_collect_wait")
        a.mark("gc_collect_restore")
        a.call("fn_gc_native_leave")
        a.mov_r64_membase_disp("rax", "rsp", 0x20)
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_collect_relock")
        a.call("fn_gc_concurrent_request")
        a.mov_r64_r64("r12", "rax")
        a.mov_membase_disp_imm32("rsp", 0x20, 0, qword=True)
        a.jmp("gc_collect_wait_enter")
        a.mark("gc_collect_relock")
        a.test_r64_r64("rbx", "rbx")
        a.jcc("e", "gc_collect_return")
        a.call("fn_heap_enter")
        # Another emergency waiter may have started a new snapshot before this
        # allocator reacquired the monitor. That snapshot temporarily hides all
        # reusable old blocks. Wait for it instead of returning a false OOM on the
        # allocator's one retry; observe idle while holding the monitor.
        a.mov_rax_rip_qword("gc_concurrent_phase")
        a.test_r64_r64("rax", "rax")
        a.jcc("e", "gc_collect_relock_owned")
        a.call("fn_heap_leave")
        a.call("fn_gc_concurrent_request")
        a.mov_r64_r64("r12", "rax")
        a.mov_membase_disp_imm32("rsp", 0x20, 0, qword=True)
        a.jmp("gc_collect_wait_enter")
        a.mark("gc_collect_relock_owned")
        a.dec_r64("rbx")
        a.jmp("gc_collect_relock")
        a.mark("gc_collect_return")
        a.add_rsp_imm8(0x28)
        a.pop_reg("r12")
        a.pop_reg("rbx")
        a.ret()
        return
