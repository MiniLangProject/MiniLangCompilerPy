"""Generate deterministic Windows/Linux/MinUX decompression stubs with GNU tools."""
from pathlib import Path
import argparse
import os
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    variants = {}
    with tempfile.TemporaryDirectory(prefix='mlc-pack-') as directory:
        for target, define in [('WINDOWS','WINDOWS_STUB'), ('LINUX','LINUX_STUB'), ('MINUX','MINUX_STUB')]:
            obj, binary = Path(directory)/'stub.o', Path(directory)/'stub.bin'
            source = ROOT/'mlc/pack_stubs/loader.S'
            def path(value):
                return subprocess.check_output(['wsl.exe','-e','wslpath','-a',str(value)],text=True).strip() if os.name=='nt' else str(value)
            prefix = ['wsl.exe','-e'] if os.name=='nt' else []
            subprocess.run(prefix+['gcc','-c','-x','assembler-with-cpp',f'-D{define}','-o',path(obj),path(source)],check=True)
            subprocess.run(prefix+['objcopy','-O','binary','-j','.text',path(obj),path(binary)],check=True)
            variants[target] = binary.read_bytes().hex()
    python = '"""Generated from pack_stubs/loader.S by tools/generate_pack_loaders.py."""\n'
    minilang = ('/* Copyright 2026 Nils Kopal.\n'
                'Licensed under the Apache License, Version 2.0.\n'
                'https://www.apache.org/licenses/LICENSE-2.0 */\n'
                '// Generated by MiniLangCompilerPy/tools/generate_pack_loaders.py.\n'
                '//! Generated native executable unpacking stubs.\npackage mlc.pack_loader_bytes\n\n')
    for name, value in variants.items():
        python += f'{name} = bytes.fromhex("{value}")\n'
        minilang += f'/// Return the generated {name.lower()} unpacking stub.\n/// @internal\nfunction {name.lower()}()\n  return fromHex("{value}")\nend function\n\n'
    minilang=minilang.rstrip()+'\n'
    for path,content in ((ROOT/'mlc/pack_loader_bytes.py',python),(ROOT.parent/'MiniLangCompilerML/mlc/pack_loader_bytes.ml',minilang)):
        if args.check:
            if path.read_text(encoding='utf-8')!=content:raise SystemExit('generated loader is stale: '+str(path))
        else:path.write_text(content,encoding='utf-8',newline='\n')
    print('Windows, Linux and MinUX pack loaders '+('verified' if args.check else 'generated'))


if __name__=='__main__':
    main()
