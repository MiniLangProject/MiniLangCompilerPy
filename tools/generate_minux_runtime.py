"""Regenerate the checked-in MinUX boundary in both compiler implementations.

GNU as is a development dependency only. Generated artifacts are checked in;
cross-compilation never invokes a host assembler or reads the MinUX SDK.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def assemble(source: Path, output: Path) -> None:
    if os.name == 'nt':
        def linux(path: Path) -> str:
            return subprocess.check_output(['wsl.exe', '-e', 'wslpath', '-a', str(path)], text=True).strip()
        command = ['wsl.exe', '-e', 'as', '--64', '-o', linux(output), linux(source)]
    else:
        command = ['as', '--64', '-o', str(output), str(source)]
    subprocess.run(command, check=True)


def fragments(image: bytes) -> dict:
    """Extract named ELF sections, folding local PC-relative relocations."""
    shoff = struct.unpack_from('<Q', image, 40)[0]
    entsize, count, names_index = struct.unpack_from('<HHH', image, 58)
    sections = [struct.unpack_from('<IIQQQQIIQQ', image, shoff+i*entsize) for i in range(count)]
    def contents(section):
        return image[section[4]:section[4]+section[5]]
    def string(table, index):
        return table[index:table.index(b'\0', index)].decode()
    names = contents(sections[names_index])
    result = {}
    for index, section in enumerate(sections):
        name = string(names, section[0])
        if name not in ('.text.startup', '.text.runtime'):
            continue
        blob = bytearray(contents(section))
        labels, patches = [], []
        for symtab in sections:
            if symtab[1] != 2:
                continue
            strings = contents(sections[symtab[6]])
            symbols = []
            for pos in range(symtab[4], symtab[4]+symtab[5], 24):
                n, info, _, sec, value, _ = struct.unpack_from('<IBBHQQ', image, pos)
                symbol = (string(strings, n), sec, value)
                symbols.append(symbol)
                if sec == index and info >> 4 == 1:
                    labels.append((symbol[0], value))
            for rela in sections:
                if rela[1] != 4 or rela[7] != index:
                    continue
                for pos in range(rela[4], rela[4]+rela[5], 24):
                    offset, info, addend = struct.unpack_from('<QQq', image, pos)
                    symbol, sec, value = symbols[info >> 32]
                    if info & 0xffffffff not in (2, 4):
                        raise ValueError(f'unsupported relocation for {symbol}')
                    if sec == index:
                        struct.pack_into('<i', blob, offset, value+addend-offset)
                    elif sec == 0 and addend == -4:
                        patches.append((offset, symbol))
                    else:
                        raise ValueError(f'unsupported cross-section relocation {symbol}')
        result[name.rsplit('.', 1)[1]] = (bytes(blob), sorted(labels, key=lambda x:(x[1], x[0])), patches)
    return result


def number_helper() -> tuple[bytes, list, list]:
    # Share the established deterministic float-to-text algorithm byte for byte.
    from types import SimpleNamespace
    from mlc.asm import Asm
    from mlc.data import DataBuilder, RDataBuilder
    from mlc.linux_runtime import emit_linux_runtime
    from mlc.tools import extern_library_label_token
    cg = SimpleNamespace(asm=Asm(), data=DataBuilder(), rdata=RDataBuilder(), extern_sigs={},
                         _extern_iat_label=lambda lib,sym: f'iat_{extern_library_label_token(lib)}_{sym}')
    emit_linux_runtime(cg)
    begin, end = cg.asm.labels['linux__gcvt'], cg.asm.labels['linux_SetConsoleOutputCP']
    blob = bytearray(cg.asm.buf[begin:end])
    for pos, target, kind in cg.asm.patches:
        if begin <= pos < end:
            if kind not in ('rel32', 'rip32') or target not in cg.asm.labels:
                raise ValueError(f'nonlocal number-helper patch: {target}')
            struct.pack_into('<i', blob, pos-begin, cg.asm.labels[target]-(pos+4))
    return bytes(blob), [('minux_number_gcvt', 0)], []


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='minux-runtime-') as work:
        obj = Path(work)/'runtime.o'
        assemble(ROOT/'mlc/minux_runtime.S', obj)
        data = fragments(obj.read_bytes())
    runtime, labels, patches = data['runtime']
    number, number_labels, _ = number_helper()
    data['runtime'] = runtime+number, labels+[(n,len(runtime)+p) for n,p in number_labels], patches
    py = '# Generated by tools/generate_minux_runtime.py; do not edit.\n'
    ml = ('/* Copyright 2026 Nils Kopal.\n'
          'Licensed under the Apache License, Version 2.0.\n'
          'https://www.apache.org/licenses/LICENSE-2.0 */\n'
          '// Generated by MiniLangCompilerPy/tools/generate_minux_runtime.py; do not edit.\n'
          '//! Generated MinUX runtime boundary bytes, labels and relocations.\npackage mlc.minux_blob\n\n')
    for name, (blob, labels, patches) in data.items():
        py += f'\n{name.upper()} = bytes.fromhex(\n'
        for i in range(0, len(blob.hex()), 120):
            py += f'    "{blob.hex()[i:i+120]}"\n'
        py += f')\n{name.upper()}_LABELS = {labels!r}\n{name.upper()}_PATCHES = {patches!r}\n'
        ml += f'/// Return the generated {name} machine-code bytes.\n/// @internal\nfunction {name}_bytes()\n  return fromHex("{blob.hex()}")\nend function\n'
        import json
        ml += f'/// Return label offsets within the generated {name} fragment.\n/// @internal\nfunction {name}_labels()\n  return {json.dumps(labels)}\nend function\n'
        ml += f'/// Return external relocations within the generated {name} fragment.\n/// @internal\nfunction {name}_patches()\n  return {json.dumps(patches)}\nend function\n\n'
    ml = ml.rstrip() + '\n'
    outputs = {ROOT/'mlc/minux_blob.py':py,
               ROOT.parent/'MiniLangCompilerML/mlc/minux_blob.ml':ml}
    for path, content in outputs.items():
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'stale MinUX runtime: {path}')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print('MinUX runtime artifacts verified' if args.check else 'MinUX runtime artifacts regenerated')


if __name__ == '__main__':
    main()
